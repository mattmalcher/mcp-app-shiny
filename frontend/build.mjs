// Bundles the browser adapter and sandbox proxy into the Python package, and
// writes the license texts of every npm package bundled into them.
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outdir = join(here, "..", "src", "shiny_mcp_host", "static");
mkdirSync(outdir, { recursive: true });

const common = {
  bundle: true,
  format: "iife",
  target: ["es2020"],
  minify: true,
  sourcemap: false,
  legalComments: "eof",
  logLevel: "info",
  metafile: true,
};

const bundles = {
  "shiny-mcp-host.js": "src/host.ts",
  "sandbox.js": "src/sandbox-proxy.ts",
};

// npm package name -> bundles it appears in
const packages = new Map();
for (const [out, entry] of Object.entries(bundles)) {
  const result = await build({ ...common, entryPoints: [join(here, entry)], outfile: join(outdir, out) });
  for (const input of Object.keys(result.metafile.inputs)) {
    const m = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (m) packages.set(m[1], new Set([...(packages.get(m[1]) ?? []), out]));
  }
}
copyFileSync(join(here, "src/styles.css"), join(outdir, "shiny-mcp-host.css"));

const notices = [
  "# Third-party licenses: shiny-mcp-host.js, sandbox.js",
  "",
  "Generated by frontend/build.mjs from the npm packages esbuild bundled into",
  "these two files (versions pinned in frontend/package-lock.json). Do not edit.",
  "mcp-app-sdk.js carries its own license in its header.",
  "",
];
for (const name of [...packages.keys()].sort()) {
  const dir = join(here, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenseFile = readdirSync(dir)
    .sort()
    .find((f) => /^licen[cs]e/i.test(f));
  const text = licenseFile ? readFileSync(join(dir, licenseFile), "utf8").trim() : "(no license file in the package)";
  notices.push(
    `## ${name} ${pkg.version}`,
    "",
    `License: ${pkg.license ?? "unspecified"}. In: ${[...packages.get(name)].sort().join(", ")}.`,
    "",
    "```text",
    text,
    "```",
    "",
  );
}
writeFileSync(join(outdir, "THIRD_PARTY_LICENSES.md"), notices.join("\n"));
