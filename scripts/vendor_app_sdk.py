"""Vendor the official MCP Apps SDK into the Python package (no Node needed).

Downloads @modelcontextprotocol/ext-apps (version pinned in frontend/package.json)
from the npm registry, verifies its sha512 integrity, and converts the SDK's
prebuilt single-file build (dist/src/app-with-deps.js, an ES module with no
imports) into src/shiny_mcp_host/static/mcp-app-sdk.js: the same code, whose
final ``export{...}`` becomes ``globalThis.McpApps = {...}`` so an inline
``<script type="module">`` can use it.

    python scripts/vendor_app_sdk.py           # (re)write the vendored file
    python scripts/vendor_app_sdk.py --check   # fail if it differs from upstream
"""

from __future__ import annotations

import base64
import hashlib
import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/shiny_mcp_host/static/mcp-app-sdk.js"
PACKAGE = "@modelcontextprotocol/ext-apps"
MEMBER = "package/dist/src/app-with-deps.js"
EXPORT = re.compile(r"export\s*\{([^}]*)\}\s*;?\s*$")


def pinned_version() -> str:
    deps = json.loads((ROOT / "frontend/package.json").read_text())["dependencies"]
    return deps[PACKAGE]


def fetch(version: str) -> tuple[str, str]:
    """Return (app-with-deps.js source, LICENSE text) from the verified tarball."""
    meta = json.load(urllib.request.urlopen(f"https://registry.npmjs.org/{PACKAGE}/{version}", timeout=60))
    dist = meta["dist"]
    data = urllib.request.urlopen(dist["tarball"], timeout=120).read()
    algo, expected = dist["integrity"].split("-", 1)
    if algo != "sha512" or base64.b64encode(hashlib.sha512(data).digest()).decode() != expected:
        sys.exit(f"Integrity check failed for {PACKAGE}@{version}")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        source = tar.extractfile(MEMBER).read().decode("utf-8")  # type: ignore[union-attr]
        license_text = tar.extractfile("package/LICENSE").read().decode("utf-8")  # type: ignore[union-attr]
    return source, license_text


def convert(source: str, version: str, license_text: str) -> str:
    source = source.rstrip()
    if re.search(r"(^|[;}\s])import[\s{*(]|import\.meta", source):
        sys.exit("The SDK build now has imports; the vendoring approach needs revisiting.")
    m = EXPORT.search(source)
    if not m or source.count("export{") + source.count("export {") != 1:
        sys.exit("Expected exactly one trailing export{...} statement in the SDK build.")
    pairs = []
    for item in m.group(1).split(","):
        local, _, exported = item.strip().partition(" as ")
        pairs.append(f"{(exported or local).strip()}:{local.strip()}")
    header = (
        f"/*! {PACKAGE}@{version} (dist/src/app-with-deps.js), vendored by shiny-mcp-host:\n"
        " * the trailing `export{...}` is replaced by `globalThis.McpApps={...}`; nothing else changed.\n"
        " * Generated by scripts/vendor_app_sdk.py; do not edit.\n *\n"
        + "".join(f" * {line}".rstrip() + "\n" for line in license_text.strip().splitlines())
        + " */\n"
    )
    return header + source[: m.start()] + "globalThis.McpApps={" + ",".join(pairs) + "};\n"


def main() -> None:
    version = pinned_version()
    source, license_text = fetch(version)
    result = convert(source, version, license_text)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != result:
            sys.exit(f"{OUT} is not the vendored {PACKAGE}@{version}; run scripts/vendor_app_sdk.py")
        print(f"{OUT.name} matches {PACKAGE}@{version}")
        return
    OUT.write_text(result, encoding="utf-8")
    print(f"wrote {OUT} ({len(result) // 1024} KB) from {PACKAGE}@{version}")


if __name__ == "__main__":
    main()
